extern bool btlWild;         // the running fight is a wild one
extern bool wildPickOpen;    // the gym chooser is showing its wild mode
// The area list is up. Implies gymOpen && gymPick && wildPickOpen; cleared
// while the team picker and the battle are on the panel.
extern bool wildAreasShown;
extern uint8_t wildAreaPage;
extern uint16_t wildArea;    // the area the team picker and the fight are for
uint8_t wildRpickMode();     // 0xFF while the area list is up: no region chooser is
void wildDrawPick(uint8_t mode);
bool wildGymTap(int16_t x, int16_t y);
void wildPickTap(int16_t x, int16_t y);
void wildPickHead(char *out, size_t n);
void wildPickBack();
void wildFight();
void wildExitToGyms();       // THE way out to the gym chooser: clears both flags
bool wildAreaSwipe(int dir); // false unless the area list is on the panel
void wildAreaTap(int16_t x, int16_t y);
void wildRenderAreas();
uint16_t wildAreaAtRow(uint8_t row);   // on the current page, WILD_NO_AREA if empty
void wildAreaRowRect(uint8_t row, int16_t &x, int16_t &y, int16_t &w, int16_t &h);   // hit area
// WILD_OK, or the pet refusal, the area's reason, or WILD_NO_SQUAD.
WildRefusal startWildBattle(uint8_t region, uint16_t area);
bool wildBattleOver();
void wildAfterBattle();
bool wildSerial(const String &line);

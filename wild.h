#pragma once
#include <Arduino.h>
#include "pet.h"

// Wild battles (fork-only, see FORK.md). Pure logic: no sketch, SD or display
// dependency, so it links into the tests exactly the way pet.cpp does.

#define WILD_ENERGY_COST 8     // spent by the live pet per battle
#define WILD_ENERGY_MIN 25     // refused below this; matches S_EXHAUSTED
#define WILD_REWARD_MIN 1      // training on a win: MIN .. MIN + SPAN - 1
#define WILD_REWARD_SPAN 2
#define WILD_REWARD_GAP 10     // a foe more than this many levels below the pet trains nothing

// Its own key in the shared "tamapoke" namespace, prefixed so an upstream key
// can never collide with it. WIPE clears it and EXPORT/IMPORT carry it.
#define WILD_SEEN_KEY "w_seen"

// Append only: the area reasons came after the pet and pack ones.
enum WildRefusal : uint8_t { WILD_OK = 0, WILD_EGG, WILD_ASLEEP, WILD_TIRED, WILD_LOCKED,
                             WILD_AREA_LOCKED, WILD_AREA_NOT_NOW, WILD_NO_SQUAD };

// ---- Encounter areas. The table is wild_areas.h, generated by tools/gen_wild.py
// from docs/*_region_pokemon_encounters.md and included by wild.cpp ONLY; these
// functions are how the sketch and the tests see it. Areas are global indices.
#define WILD_NO_AREA 0xFFFF
#define WILD_NAME_MAX 15        // wild_areas.h asserts the generator agrees
#define WILD_TM_MORNING 1       // slot time masks, and what wildTimeMask() returns
#define WILD_TM_DAY 2
#define WILD_TM_NIGHT 4
#define WILD_TM_ALL 7
#define WILD_MORNING_FROM 4     // HGSS windows for every region: morning 04-10,
#define WILD_DAY_FROM 10        // day 10-20, night 20-04
#define WILD_NIGHT_FROM 20

struct WildSlotView { int16_t dex; uint16_t weight; uint8_t tier, lo, hi, tmask; };

uint16_t wildAreaFirst(uint8_t r);
uint16_t wildAreaCount(uint8_t r);
const char *wildAreaName(uint16_t a);
uint8_t wildAreaTier(uint16_t a);
uint8_t wildAreaRegion(uint16_t a);
const char *wildTierTitle(uint8_t r, uint8_t tier);   // "" if the tier has no title
uint16_t wildSlotCount(uint16_t a);
bool wildSlotAt(uint16_t a, uint16_t i, WildSlotView &out);
uint16_t wildSlotTotal();   // every slot in the table, for the tests

bool wildRegionHasAreas(uint8_t r);
// 1 + the longer consecutive run from gym 0, easy and hard counted SEPARATELY
// (as gymUnlocked() does) and capped at TRAINER_GYMS: 1..TRAINER_GYMS + 1.
uint8_t wildTier(const Pet &p, uint8_t r);
int8_t wildHour(const Pet &p);          // -1 with no clock
uint8_t wildTimeMask(const Pet &p);     // WILD_TM_ALL with no clock
// A slot is live when its area's tier and its own are unlocked, its time mask
// matches and its species is playable. Open = at least one live slot.
bool wildAreaOpen(const Pet &p, uint16_t a);
// WILD_OK when open, else the first filter that empties it: tier
// (WILD_AREA_LOCKED), then time (WILD_AREA_NOT_NOW), then pack (WILD_LOCKED).
WildRefusal wildAreaWhyClosed(const Pet &p, uint16_t a);
// The same rule over arbitrary slots: no area in the documents can read
// NOT_NOW, so this is how the tests reach that branch.
WildRefusal wildWhyClosedOf(const WildSlotView *s, uint16_t n, uint8_t areaTier, uint8_t tier, uint8_t tm);
// Weighted pick over the live slots, level uniform in the slot's range.
// -1 (and lvl 0) when the area is closed.
int16_t wildRollArea(const Pet &p, uint16_t a, uint8_t &lvl);
void wildAreaLevels(const Pet &p, uint16_t a, uint8_t &lo, uint8_t &hi);   // 0,0 when closed
uint16_t wildRandomOpenArea(const Pet &p, uint8_t r);   // WILD_NO_AREA when none is open

WildRefusal wildCanStart(const Pet &p, uint8_t region);
void wildSpend(Pet &p);
// Area levels do not follow the squad, so a foe this far below the pet is free
// training. wildReward() and the battle log both ask this.
bool wildTooEasy(const Pet &p, uint8_t foeLvl);
// Training for the live pet, only on a win it fought in against a foe that is
// not wildTooEasy(). Returns what was gained (0 = nothing) and writes the stat
// into `which` (0 ATK, 1 DEF, 2 SPE).
uint8_t wildReward(Pet &p, bool won, bool petFought, uint8_t foeLvl, uint8_t &which);

// Seen-in-the-wild bitmap. Loading never writes; a bit is written only the
// first time a species is met, so flashing the fork changes nothing in NVS.
void wildLoad();
void wildMarkSeen(int16_t d);
bool wildSeen(const Pet &p, int16_t d);   // met in the wild OR raised
uint16_t wildSeenCountIn(const Pet &p, uint8_t region);

// Fork-owned strings, kept out of upstream's positional STRINGS table so its
// appends can never shift ours. ASCII only, like every firmware string.
enum WildStr : uint8_t {
  W_BTN, W_TITLE, W_APPEARED, W_GAIN,
  W_NO_EGG, W_NO_SLEEP, W_NO_ENERGY, W_NO_PACK,
  W_NOT_NOW, W_LV_FMT, W_NEED_BADGE_FMT, W_NO_AREA,
  W_TOO_EASY,
  W_COUNT
};
const char *WT(WildStr s);
const char *wildRefusalText(WildRefusal r);
// A closed area row's right column: "Badge n" (the badge its tier needs),
// "Not now" or "Needs pack". Size-1 text, so at most WILD_ROW_REASON_MAX.
void wildRowReason(WildRefusal r, uint8_t areaTier, char *out, size_t n);
#define WILD_ROW_REASON_MAX 16
#define WILD_ROW_LV_MAX 8       // an open row's W_LV_FMT, at size 2

// ---- Sketch-only UI, defined in wild_ui.h (included at the bottom of
// TamaPoke.ino). Declared here because the FORK(wild) hooks above that include
// call them, and arduino-cli only auto-prototypes the .ino itself.
#define RPICK_FOR_WILD 3     // next to RPICK_FOR_GYMS/DEX/START in the sketch
